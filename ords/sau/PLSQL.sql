CREATE OR REPLACE TYPE T_REGION AS OBJECT (
    CODIGO_REGION NUMBER(15),
    NOMBRE        VARCHAR2(80)
);
/

CREATE OR REPLACE TYPE T_REGION_ARRAY AS TABLE OF T_REGION;
/

CREATE OR REPLACE FUNCTION FN_LISTAR_REGIONES
RETURN T_REGION_ARRAY
IS
    V_REGIONES T_REGION_ARRAY;
BEGIN
    SELECT T_REGION(CODIGO_REGION, NOMBRE)
    BULK COLLECT INTO V_REGIONES
    FROM REGION
    ORDER BY CODIGO_REGION;

    RETURN V_REGIONES;
END;
/
